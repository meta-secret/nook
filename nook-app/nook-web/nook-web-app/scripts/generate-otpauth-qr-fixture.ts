/**
 * Regenerates the checked-in QR module grids that test pages render, so ZXing
 * decodes genuine QR codes instead of a page-provided marker:
 * - tests/fixtures/otpauth-qr-modules.ts for the 2FA dialog demo;
 * - the extension mock-auth authenticator setup dialog's grid.
 *
 * Run from nook-web-app: `bun scripts/generate-otpauth-qr-fixture.ts`.
 */
import { writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { format, resolveConfig } from 'prettier'
import { prepareZXingModule, writeBarcode } from 'zxing-wasm/writer'

/** A demo-only authenticator; the secret is the RFC 4648 "Hello!\xDE\xAD\xBE\xEF" sample. */
const OTPAUTH_QR_TEXT =
  'otpauth://totp/Demo%20Service:demo.user%40example.test?secret=JBSWY3DPEHPK3PXP&issuer=Demo%20Service&algorithm=SHA1&digits=6&period=30'

/** The mock-auth enrollment account (accounts.ts), same payload as public/totp-enroll-qr.png. */
const MOCK_AUTH_ENROLL_QR_TEXT =
  'otpauth://totp/Mock%20Auth:alice-2fa%40nook.test?secret=JBSWY3DPEHPK3PXP&issuer=Mock%20Auth&algorithm=SHA1&digits=6&period=30'

/** ZXing writes 0 for a dark module and 255 for a light one. */
const DARK_MODULE = 0

type QrFixture = {
  readonly name: string
  readonly text: string
}

type QrFixtureFile = {
  readonly output: string
  readonly fixtures: readonly QrFixture[]
}

function moduleGlyph(module: number): string {
  switch (module) {
    case DARK_MODULE:
      return '#'
    default:
      return '.'
  }
}

const files: readonly QrFixtureFile[] = [
  {
    output: join(import.meta.dir, '../tests/fixtures/otpauth-qr-modules.ts'),
    fixtures: [{ name: 'OTPAUTH_QR', text: OTPAUTH_QR_TEXT }],
  },
  {
    output: join(
      import.meta.dir,
      '../../nook-web-extension/e2e/mock-auth/src/lib/otpauth-qr-modules.ts',
    ),
    fixtures: [{ name: 'MOCK_AUTH_ENROLL_QR', text: MOCK_AUTH_ENROLL_QR_TEXT }],
  },
]

const writerWasm = await Bun.file(
  Bun.resolveSync('zxing-wasm/writer/zxing_writer.wasm', import.meta.dir),
).arrayBuffer()
await prepareZXingModule({
  overrides: { wasmBinary: writerWasm },
  fireImmediately: true,
})

async function fixtureSection(fixture: QrFixture): Promise<string> {
  const written = await writeBarcode(fixture.text, {
    format: 'QRCode',
    ecLevel: 'M',
  })
  switch (written.error.length) {
    case 0:
      break
    default:
      throw new Error(`Could not encode ${fixture.name}: ${written.error}`)
  }
  const { data, width, height } = written.symbol
  const rows: string[] = []
  for (let row = 0; row < height; row += 1) {
    const modules = data.subarray(row * width, (row + 1) * width)
    rows.push(Array.from(modules, moduleGlyph).join(''))
  }
  return (
    `export const ${fixture.name}_TEXT =\n  '${fixture.text}'\n\n` +
    `export const ${fixture.name}_MODULES: QrModuleRows = [\n` +
    rows.map((row) => `  '${row}',\n`).join('') +
    `]\n`
  )
}

for (const file of files) {
  const sections: string[] = []
  for (const fixture of file.fixtures) {
    sections.push(await fixtureSection(fixture))
  }
  const source =
    `// Generated by nook-web-app/scripts/generate-otpauth-qr-fixture.ts; do not edit.\n` +
    `/** Rows of QR modules without the quiet zone: "#" is dark, "." is light. */\n` +
    `export type QrModuleRows = readonly string[]\n\n` +
    sections.join('\n')
  // Emit the repository's formatting so the checked-in fixture passes format checks.
  const prettierConfig = await resolveConfig(file.output)
  await writeFile(
    file.output,
    await format(source, { ...prettierConfig, filepath: file.output }),
  )
  console.log(`Wrote ${file.output}`)
}
