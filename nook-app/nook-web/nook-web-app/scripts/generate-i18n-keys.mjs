function flattenCatalog(value, prefix = [], entries = []) {
  for (const [segment, child] of Object.entries(value)) {
    const path = [...prefix, segment]
    if (typeof child === 'string') entries.push(path.join('.'))
    else if (child && typeof child === 'object' && !Array.isArray(child)) {
      flattenCatalog(child, path, entries)
    } else
      throw new Error(
        `translation ${path.join('.')} must be a string or object`,
      )
  }
  return entries
}

function words(key) {
  return key.split(/[^A-Za-z0-9]+/).filter(Boolean)
}

function typescriptName(key) {
  return words(key)
    .map((word) => `${word[0].toUpperCase()}${word.slice(1)}`)
    .join('')
}

function rustName(key) {
  return words(key)
    .map((word) => word.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase())
    .join('_')
}

function typescriptString(value) {
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`
}

function validateNames(keys, naming, language) {
  const owners = new Map()
  for (const key of keys) {
    const name = naming(key)
    const existing = owners.get(name)
    if (existing)
      throw new Error(
        `${language} name collision: ${existing} and ${key} -> ${name}`,
      )
    owners.set(name, key)
  }
}

function typescriptSource(keys) {
  const importPrefixes = [
    'apple_passwords_import',
    'chrome_passwords_import',
    'dashlane_import',
    'keepassxc_import',
    'keeper_import',
    'lastpass_import',
    'onepassword_import',
    'proton_pass_import',
  ]
  const importSuffixes = [
    'title',
    'description',
    'export_hint_title',
    'export_hint',
    'file_label',
    'supported_types',
    'importing',
    'import',
    'result_imported',
    'result_skipped',
  ]
  const importGroupNames = {
    apple_passwords_import: 'ApplePasswords',
    chrome_passwords_import: 'ChromePasswords',
    dashlane_import: 'Dashlane',
    keepassxc_import: 'KeePassXc',
    keeper_import: 'Keeper',
    lastpass_import: 'LastPass',
    onepassword_import: 'OnePassword',
    proton_pass_import: 'ProtonPass',
  }
  const importKeyRows = importPrefixes.flatMap((prefix) => [
    `  ${importGroupNames[prefix]}: {`,
    ...importSuffixes.map(
      (suffix) =>
        `    ${suffix.replace(/_([a-z])/g, (_, letter) => letter.toUpperCase())}: I18N_KEYS.${typescriptName(`${prefix}.${suffix}`)},`,
    ),
    '  },',
  ])
  return [
    '// @generated by scripts/generate-i18n-keys.mjs; do not edit.',
    '// The Rust-owned locale catalogs are the source of truth.',
    'export const I18N_KEYS = {',
    ...keys.map((key) => `  ${typescriptName(key)}: ${typescriptString(key)},`),
    '} as const',
    '',
    'export type I18nKey = (typeof I18N_KEYS)[keyof typeof I18N_KEYS]',
    'export type I18nTranslator = (',
    '  key: I18nKey,',
    '  replacements?: Record<string, string>,',
    ') => string',
    '',
    'export type PasswordImportMessageKeys = {',
    ...importSuffixes.map(
      (suffix) =>
        `  ${suffix.replace(/_([a-z])/g, (_, letter) => letter.toUpperCase())}: I18nKey`,
    ),
    '}',
    '',
    'export const PASSWORD_IMPORT_MESSAGE_KEYS = {',
    ...importKeyRows,
    '} as const satisfies Record<string, PasswordImportMessageKeys>',
    '',
  ].join('\n')
}

function landingTypescriptSource(keys) {
  return [
    '// @generated by scripts/generate-i18n-keys.mjs; do not edit.',
    '// The standalone landing-page catalog is the source of truth.',
    'export const LANDING_MESSAGE_KEYS = {',
    ...keys.map((key) => `  ${typescriptName(key)}: ${typescriptString(key)},`),
    '} as const',
    '',
    'export type LandingMessageKey =',
    '  (typeof LANDING_MESSAGE_KEYS)[keyof typeof LANDING_MESSAGE_KEYS]',
    '',
  ].join('\n')
}

function rustSource(keys) {
  const declarations = keys.map((key) => {
    const declaration = `pub const ${rustName(key)}: &str = ${JSON.stringify(key)};`
    return declaration.length <= 100
      ? declaration
      : `pub const ${rustName(key)}: &str =\n    ${JSON.stringify(key)};`
  })
  return [
    '// @generated by nook-web-app/scripts/generate-i18n-keys.mjs; do not edit.',
    '// The Rust-owned locale catalogs are the source of truth.',
    ...declarations,
    '',
  ].join('\n')
}

async function readCatalog(locale) {
  return JSON.parse(
    await readFile(resolve(localeDirectory, `${locale}.json`), 'utf8'),
  )
}

function compareCatalogKeys(englishKeys, russianKeys) {
  const english = new Set(englishKeys)
  const russian = new Set(russianKeys)
  const missingRussian = englishKeys.filter((key) => !russian.has(key))
  const missingEnglish = russianKeys.filter((key) => !english.has(key))
  if (missingRussian.length || missingEnglish.length) {
    throw new Error(
      `locale key mismatch\nmissing from ru: ${missingRussian.join(', ')}\nmissing from en: ${missingEnglish.join(', ')}`,
    )
  }
}

async function verifyOutput(path, expected) {
  let actual = ''
  try {
    actual = await readFile(path, 'utf8')
  } catch {
    // A missing generated file is reported as drift below.
  }
  if (actual !== expected) {
    throw new Error(
      `${relative(repositoryRoot, path)} is stale; run bun run i18n:keys:generate`,
    )
  }
}

const sourceExtensions = new Set([
  '.js',
  '.mjs',
  '.rs',
  '.svelte',
  '.ts',
  '.tsx',
])
const excludedDirectories = new Set([
  '.git',
  '.svelte-kit',
  'coverage',
  'dist',
  'node_modules',
  'target',
])

async function sourceFiles(directory, files = []) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.isDirectory() && excludedDirectories.has(entry.name)) continue
    const path = resolve(directory, entry.name)
    if (entry.isDirectory()) await sourceFiles(path, files)
    else if (entry.isFile() && sourceExtensions.has(extname(entry.name)))
      files.push(path)
  }
  return files
}

function literalValues(source) {
  const values = []
  const pattern = /(['"])((?:\\.|(?!\1).)*)\1/g
  for (const match of source.matchAll(pattern)) {
    if (!match[2].includes('\\')) values.push(match[2])
  }
  return values
}

async function verifyNoRawCanonicalKeys(keys) {
  const canonical = new Set(keys)
  const allowed = new Set([typescriptOutput, rustOutput])
  const violations = []
  for (const path of await sourceFiles(resolve(repositoryRoot, 'nook-app'))) {
    if (allowed.has(path)) continue
    const source = await readFile(path, 'utf8')
    const rawKeys = [
      ...new Set(literalValues(source).filter((value) => canonical.has(value))),
    ]
    if (rawKeys.length)
      violations.push(
        `${relative(repositoryRoot, path)}: ${rawKeys.join(', ')}`,
      )
  }
  if (violations.length) {
    throw new Error(
      `raw canonical translation keys found:\n${violations.join('\n')}`,
    )
  }
}

async function verifyNoObsoleteRustKeyRegistries() {
  const violations = []
  for (const path of obsoleteRustOutputs) {
    try {
      await readFile(path, 'utf8')
      violations.push(relative(repositoryRoot, path))
    } catch (error) {
      if (error?.code !== 'ENOENT') throw error
    }
  }
  if (violations.length) {
    throw new Error(
      `obsolete per-crate Rust translation-key registries found:\n${violations.join('\n')}`,
    )
  }
}

async function verifyNoLiteralLookupArguments() {
  const violations = []
  const lookup =
    /(?:\b(?:t|translatedMessage|translatedMessageWithSubstitution|translateFromCatalog|translateWithReplacements)\s*\(|\.t\s*\(|chrome\.i18n\.getMessage\s*\()\s*(["'`])/g
  for (const path of await sourceFiles(resolve(repositoryRoot, 'nook-app'))) {
    if (path === fileURLToPath(import.meta.url)) continue
    const source = await readFile(path, 'utf8')
    for (const match of source.matchAll(lookup)) {
      const line = source.slice(0, match.index).split('\n').length
      violations.push(`${relative(repositoryRoot, path)}:${line}`)
    }
  }
  if (violations.length) {
    throw new Error(
      `literal translation lookup keys found; use a key registry:\n${violations.join('\n')}`,
    )
  }
}

async function verifyNoRawBrowserMessageKeys() {
  const registrySource = await readFile(browserMessageKeysPath, 'utf8')
  const browserKeys = new Set(
    literalValues(registrySource).filter(
      (value) => value.startsWith('widget') || value.startsWith('passkey'),
    ),
  )
  const violations = []
  const extensionSource = resolve(
    repositoryRoot,
    'nook-app/nook-web/nook-web-extension/src',
  )
  for (const path of await sourceFiles(extensionSource)) {
    if (path === browserMessageKeysPath) continue
    const source = await readFile(path, 'utf8')
    const rawKeys = [
      ...new Set(
        literalValues(source).filter((value) => browserKeys.has(value)),
      ),
    ]
    if (rawKeys.length)
      violations.push(
        `${relative(repositoryRoot, path)}: ${rawKeys.join(', ')}`,
      )
  }
  if (violations.length) {
    throw new Error(
      `raw browser translation keys found:\n${violations.join('\n')}`,
    )
  }
}

async function landingKeys() {
  const source = await readFile(landingMessagesPath, 'utf8')
  const moduleUrl = `data:text/javascript;base64,${Buffer.from(source).toString('base64')}`
  // The URL contains only the local translation catalog read immediately above.
  // eslint-disable-next-line no-unsanitized/method
  const { landingMessages } = await import(moduleUrl)
  const englishKeys = Object.keys(landingMessages.en).sort()
  const russianKeys = Object.keys(landingMessages.ru).sort()
  compareCatalogKeys(englishKeys, russianKeys)
  validateNames(englishKeys, typescriptName, 'landing TypeScript')
  return englishKeys
}

const englishKeys = flattenCatalog(await readCatalog('en')).sort()
const russianKeys = flattenCatalog(await readCatalog('ru')).sort()
compareCatalogKeys(englishKeys, russianKeys)
validateNames(englishKeys, typescriptName, 'TypeScript')
validateNames(englishKeys, rustName, 'Rust')

const generatedTypescript = typescriptSource(englishKeys)
const generatedRust = rustSource(englishKeys)
const generatedLandingTypescript = landingTypescriptSource(await landingKeys())
if (checkOnly) {
  await verifyOutput(typescriptOutput, generatedTypescript)
  await verifyOutput(rustOutput, generatedRust)
  await verifyOutput(landingOutput, generatedLandingTypescript)
  await verifyNoObsoleteRustKeyRegistries()
  await verifyNoRawCanonicalKeys(englishKeys)
  await verifyNoRawBrowserMessageKeys()
  await verifyNoLiteralLookupArguments()
} else {
  await mkdir(dirname(typescriptOutput), { recursive: true })
  await mkdir(dirname(rustOutput), { recursive: true })
  await mkdir(dirname(landingOutput), { recursive: true })
  await writeFile(typescriptOutput, generatedTypescript)
  await writeFile(rustOutput, generatedRust)
  await writeFile(landingOutput, generatedLandingTypescript)
}
