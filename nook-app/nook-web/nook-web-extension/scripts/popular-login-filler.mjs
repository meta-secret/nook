/** Large filler set: brand slug + apex host → research template by sector. */
function sectorTemplate(sector) {
  switch (sector) {
    case 'bank':
      return 'username-password'
    case 'saas':
      return 'email-first'
    case 'telecom':
      return 'tel-password'
    case 'health':
      return 'member-id-password'
    case 'hr':
      return 'employee-id-password'
    case 'fintech':
      return 'email-password'
    case 'mfa':
      return 'password-then-otp'
    case 'sso':
      return 'enterprise-sso-email'
    case 'phone':
      return 'phone-first'
    case 'pin':
      return 'pin-login'
    case 'account':
      return 'account-number-password'
    case 'dual':
      return 'dual-identity-password'
    case 'hidden':
      return 'email-password-aria-hidden'
    case 'userfirst':
      return 'username-first'
    default:
      return 'email-password'
  }
}

function slugify(name) {
  return name
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
}

